pub const fn pull_field(bank:u8,pin:u8)->Option<PinField>{let g=bank as u32*32+pin as u32;match select_pin_reg(PULL_REGS,g){Some(e)=>Some(PinField{reg:e.reg+((g-e.first_pin)/8)*4,bit:(pin%8)*2,width:2}),None=>None}}
pub const fn drive_field(bank:u8,pin:u8)->Option<PinField>{let g=bank as u32*32+pin as u32;match select_pin_reg(DRIVE_REGS,g){Some(e)=>Some(PinField{reg:e.reg+((g-e.first_pin)/4)*4,bit:(pin%4)*4,width:4}),None=>None}}
pub const fn schmitt_field(bank:u8,pin:u8)->Option<PinField>{let g=bank as u32*32+pin as u32;match select_pin_reg(SCHMITT_REGS,g){Some(e)=>Some(PinField{reg:e.reg+((g-e.first_pin)/8)*4,bit:pin%8,width:1}),None=>None}}
